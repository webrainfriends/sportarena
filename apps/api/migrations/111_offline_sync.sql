-- Offline player capture and reliable synchronisation (issue #336). Additive only: nothing is dropped, rewritten or cascaded.
-- Players capture match logs, workout logs and training loads on a device with no signal; the device queues them as encrypted
-- drafts and uploads them in batches. Every operation carries a client_key, so a retried upload never creates a second record.

-- 1. Match logs become idempotent and versioned (existing rows keep row_version 1 and no key).
ALTER TABLE player_matches ADD COLUMN IF NOT EXISTS client_key text;
ALTER TABLE player_matches ADD COLUMN IF NOT EXISTS row_version int NOT NULL DEFAULT 1;
ALTER TABLE player_matches ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();
CREATE UNIQUE INDEX IF NOT EXISTS player_matches_client_key ON player_matches (user_id, client_key) WHERE client_key IS NOT NULL;

-- Every earlier state of a match log that a sync or a conflict resolution replaced stays here (encrypted: it holds free text).
CREATE TABLE IF NOT EXISTS player_match_revisions (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  match_id     uuid NOT NULL REFERENCES player_matches,
  row_version  int NOT NULL,
  snapshot_enc text NOT NULL,
  reason       text NOT NULL CHECK (reason IN ('sync_update','conflict_keep_mine','conflict_merge')),
  created_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (match_id, row_version)
);

-- 2. Training loads become idempotent.
ALTER TABLE session_loads ADD COLUMN IF NOT EXISTS client_key text;
CREATE UNIQUE INDEX IF NOT EXISTS session_loads_client_key ON session_loads (user_id, client_key) WHERE client_key IS NOT NULL;

-- 3. Devices that sync for a player. Revoking one signs its login session out and tells it to wipe its drafts the next time it connects.
CREATE TABLE IF NOT EXISTS sync_devices (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id       uuid NOT NULL REFERENCES users,
  device_id     text NOT NULL CHECK (length(device_id) BETWEEN 8 AND 64),   -- generated by the app, stable per install
  label         text CHECK (length(label) <= 60),
  platform      text NOT NULL DEFAULT 'web' CHECK (platform IN ('ios','ipados','android','web')),
  session_id    uuid,                                                      -- login session seen on the last sync
  registered_at timestamptz NOT NULL DEFAULT now(),
  last_sync_at  timestamptz,
  last_queued   int NOT NULL DEFAULT 0,
  revoked_at    timestamptz,
  UNIQUE (user_id, device_id)
);

-- 4. The ledger of uploaded operations: one row per (player, client_key). Applied rows keep only the outcome; conflicting and
--    refused rows keep the player's draft (encrypted) until they decide what to do, and a resolved conflict keeps the losing version.
CREATE TABLE IF NOT EXISTS sync_operations (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id      uuid NOT NULL REFERENCES users,
  device_id    text,
  client_key   text NOT NULL CHECK (length(client_key) BETWEEN 8 AND 80),
  kind         text NOT NULL CHECK (kind IN ('match_create','match_update','workout_log','load_log')),
  status       text NOT NULL CHECK (status IN ('applied','conflict','rejected','resolved')),
  target_id    uuid,
  base_version int,
  captured_at  timestamptz,
  payload_enc  text,
  result       jsonb,
  reason_code  text,
  reason       text,
  resolution   text CHECK (resolution IN ('keep_mine','keep_server','merge')),
  attempts     int NOT NULL DEFAULT 1,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  resolved_at  timestamptz,
  UNIQUE (user_id, client_key)
);
CREATE INDEX IF NOT EXISTS sync_operations_user_status ON sync_operations (user_id, status, created_at DESC, id);
