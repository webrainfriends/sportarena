// Variable types. `link` is always generated by the server (an authorised in-app deep link); it can never be supplied.
const TIMEZONE = 'Asia/Kolkata';
// a name that carries a web address (or something that reads like one) is never sent: an event called "Win now bit.ly/x" must not become a phishing text
const URLISH = /(https?:|www\.|\b[a-z0-9-]{2,}\.(com|in|co|net|org|io|ly|me|app|link|xyz|info|biz|online|site|top|club|live)\b|@[a-z0-9_]{2,}|\/\/)/i;
const safeText = (v, max, what) => { const s = clean(v, max); if (!s) throw badRequest(`empty ${what}`); if (URLISH.test(s)) throw badRequest(`${what} looks like a link`); return s; };
export const hasWebAddress = (text) => URLISH.test(String(text));
const clean = (s, max) => String(s ?? '').replace(/[\u0000-\u001f\u007f\u2028\u2029]/g, ' ').replace(/\s+/g, ' ').trim().slice(0, max);
export const VAR_TYPES = {
  name: (v) => safeText(v, 40, 'name'),
  label: (v) => safeText(v, 60, 'label'),
  currency: (v) => {
    if (!v || !Number.isInteger(v.minor) || v.minor < 0 || !Object.hasOwn(CURRENCIES, v.currency)) throw badRequest('bad amount');
    const e = exponent(v.currency);
    return `${CURRENCIES[v.currency].symbol}${new Intl.NumberFormat('en-IN', { minimumFractionDigits: e ? (v.minor % 10 ** e ? e : 0) : 0, maximumFractionDigits: e }).format(v.minor / 10 ** e)}`;
  },
  date: (v) => {
    const d = new Date(`${String(v).slice(0, 10)}T00:00:00Z`);
    if (Number.isNaN(d.getTime())) throw badRequest('bad date');
    return new Intl.DateTimeFormat('en-IN', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' }).format(d);
  },
  datetime: (v) => {
    const d = new Date(v);
    if (Number.isNaN(d.getTime())) throw badRequest('bad date and time');
    return new Intl.DateTimeFormat('en-IN', { day: 'numeric', month: 'short', hour: 'numeric', minute: '2-digit', hour12: true, timeZone: TIMEZONE }).format(d);
  },
  code: (v) => { if (!/^\d{4,8}$/.test(String(v))) throw badRequest('bad code'); return String(v); },
  link: (v) => { if (!/^https?:\/\/[^\s]+$/.test(String(v))) throw badRequest('bad link'); return String(v); },
};
