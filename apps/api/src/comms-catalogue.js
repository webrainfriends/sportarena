const BY_KIND = new Map(Object.entries(USE_CASES).flatMap(([k, u]) => u.kinds.map((kind) => [kind, k])));
export const useCaseForKind = (kind) => BY_KIND.get(kind) ?? null;
export const categoryOf = (useCase) => USE_CASES[useCase]?.category ?? null;

/** Names `{{x}}` used in a template body, in order of first use. */
export const placeholdersOf = (body) => [...new Set([...String(body).matchAll(/\{\{\s*([a-z][a-z0-9_]*)\s*\}\}/g)].map((m) => m[1]))];

/**
 * Check a template definition against the catalogue: every declared variable belongs to the use case with the right type, every
 * placeholder in the body is declared, and nothing declared is left unused. Returns the normalised variable list.
 */
export function checkTemplate({ use_case, body, variables }) {
  const uc = USE_CASES[use_case];
  if (!uc) throw badRequest('Unknown use case');
  const declared = new Map();
  for (const v of variables) {
    if (declared.has(v.name)) throw badRequest(`Variable ${v.name} is declared twice`);
    if (!Object.hasOwn(uc.vars, v.name)) throw badRequest(`${v.name} is not available for "${uc.label}". Allowed: ${Object.keys(uc.vars).join(', ')}`);
    if (uc.vars[v.name] !== v.type) throw badRequest(`${v.name} must be of type ${uc.vars[v.name]}`);
    declared.set(v.name, v);
  }
  const used = placeholdersOf(body);
  for (const p of used) if (!declared.has(p)) throw badRequest(`{{${p}}} is used in the message but not declared as a variable`);
  for (const n of declared.keys()) if (!used.includes(n)) throw badRequest(`${n} is declared but not used in the message`);
  if (/\{\{|\}\}/.test(body.replace(/\{\{\s*[a-z][a-z0-9_]*\s*\}\}/g, ''))) throw badRequest('Stray braces in the message');
  return used.map((n) => ({ name: n, type: uc.vars[n] }));
}

/** Validate and format the values for a template's variables. Throws when one is missing or malformed (the message is then not sent). */
export function formatVars(variables, values) {
  const out = {};
  for (const v of variables) {
    const fail = (kind, why) => Object.assign(badRequest(`${kind} ${v.name}${why ? `: ${why}` : ''}`), { variable: v.name, kind });
    if (values?.[v.name] === undefined || values[v.name] === null) throw fail('missing');
    try { out[v.name] = VAR_TYPES[v.type](values[v.name]); } catch (e) { throw fail('invalid', e.message); }
  }
  return out;
}

export const renderBody = (body, formatted) => body.replace(/\{\{\s*([a-z][a-z0-9_]*)\s*\}\}/g, (_, n) => formatted[n] ?? '');
