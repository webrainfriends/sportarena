// which typed variables a template for them may use. Pure (no database), so it is the one place a reviewer checks what can leak.
//
// Private by default: a notification kind that is not mapped here never goes to WhatsApp Business or SMS. Variables are typed and
// system-resolved (see comms.js `resolveVars`); a caller's free text (titles, bodies, notes, reasons) can never become a variable.
